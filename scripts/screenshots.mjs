// Usage: node scripts/screenshots.mjs [baseUrl]
import { chromium, devices } from 'playwright'
const base = process.argv[2] || 'http://localhost:4173/'
const out = 'screenshots'
const b = await chromium.launch()
const ctx = await b.newContext({ ...devices['iPhone 13'], viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const p = await ctx.newPage()
const errors = []
p.on('pageerror', (e) => errors.push(e.message))
p.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
await p.goto(base + '#battle', { waitUntil: 'networkidle' })
await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: 'networkidle' })
await p.waitForTimeout(500)
await p.screenshot({ path: `${out}/1-battle.png` })

// Roll initiative
await p.getByRole('button', { name: /Roll Initiative/ }).click()
await p.getByRole('button', { name: /Roll everyone/ }).click()
await p.getByRole('button', { name: /Start combat/ }).click()
await p.waitForTimeout(500)
await p.screenshot({ path: `${out}/2-battle-initiative.png` })

// Drag Goblin 1's sword handle onto Thorin (mouse pointer events)
const card = (name) => p.locator('.ccard', { hasText: name }).first()
const handle = card('Goblin 1').locator('.drag-handle')
const hb = await handle.boundingBox(); const tb = await card('Thorin').boundingBox()
await p.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2); await p.mouse.down()
await p.mouse.move(hb.x - 60, hb.y - 20, { steps: 5 })
await p.mouse.move(tb.x + tb.width / 2, tb.y + tb.height / 2, { steps: 10 })
await p.screenshot({ path: `${out}/3-battle-dragging.png` })
await p.mouse.up()
await p.waitForTimeout(400)
await p.locator('.dtype', { hasText: 'bludgeoning' }).click()
await p.locator('.sheet input[value="Scimitar"]').fill('Club')
await p.locator('.sheet .stepper input').last().fill('5')
await p.waitForTimeout(400)
await p.screenshot({ path: `${out}/4-attack-reminder-bludgeoning.png` })
await p.locator('.sheet-body').evaluate((e) => e.scrollTo(0, 0)); await p.waitForTimeout(200)
await p.screenshot({ path: `${out}/4a-attack-sheet-top.png` })
const reminder = await p.locator('.reminder').innerText()
await p.locator('.sheet-foot .btn').click()
await p.waitForTimeout(300)

// Tap-tap fallback: Thorin -> Skeleton with Warhammer (bludgeoning, vulnerable)
await card('Thorin').locator('.ccard-name').click()
await card('Skeleton').locator('.ccard-name').click()
await p.waitForTimeout(300)
await p.locator('.sheet .stepper input').last().fill('6')
await p.waitForTimeout(200)
await p.screenshot({ path: `${out}/5-attack-vulnerable.png` })
await p.locator('.sheet-foot .btn').click()
await p.waitForTimeout(1300)
const log = await p.locator('.log ul').innerText()
await p.screenshot({ path: `${out}/6-battle-after.png` })
await p.locator('.log').scrollIntoViewIfNeeded(); await p.screenshot({ path: `${out}/6b-combat-log.png` })

await p.locator('.tabbar button', { hasText: 'Characters' }).click(); await p.waitForTimeout(400)
await p.screenshot({ path: `${out}/7-characters.png` })
await p.locator('.char-card', { hasText: 'Thorin' }).click(); await p.waitForTimeout(400)
await p.screenshot({ path: `${out}/8-character-sheet.png` })
await p.locator('.sheet-head .icon-btn').click()

await p.locator('.tabbar button', { hasText: 'Dice' }).click(); await p.waitForTimeout(300)
await p.locator('.die-btn.d6').click(); await p.locator('.die-btn.d6').click()
await p.getByRole('button', { name: /^ROLL/ }).click(); await p.waitForTimeout(1000)
await p.getByRole('button', { name: /^ROLL/ }).click(); await p.waitForTimeout(1000)
await p.screenshot({ path: `${out}/9-dice.png` })

await p.locator('.tabbar button', { hasText: 'Campaign' }).click(); await p.waitForTimeout(400)
await p.screenshot({ path: `${out}/10-campaign.png` })
await p.locator('.page-card').first().click(); await p.waitForTimeout(400)
await p.screenshot({ path: `${out}/11-campaign-page.png` })

// SRD monster search: add 2 zombies
await p.locator('.sheet-head .icon-btn').click(); await p.waitForTimeout(200)
await p.locator('.tabbar button', { hasText: 'Battle' }).click(); await p.waitForTimeout(300)
await p.getByRole('button', { name: 'Add monster' }).click()
await p.locator('.sheet input.search').fill('zombie'); await p.waitForTimeout(1500)
await p.screenshot({ path: `${out}/12-srd-search.png` })
await p.locator('.results .list-row', { hasText: /^Zombie/ }).first().click(); await p.waitForTimeout(1500)
await p.locator('.sheet-foot .stepper input').fill('2')
await p.screenshot({ path: `${out}/13-srd-prefilled.png` })
await p.locator('.sheet-foot .btn.primary').click(); await p.waitForTimeout(400)
console.log('MONSTERS:', await p.locator('.col').nth(1).locator('.ccard-name b').allInnerTexts())
console.log('REMINDER:', reminder)
console.log('LOG:', log)
console.log('ERRORS:', errors)
await b.close()
